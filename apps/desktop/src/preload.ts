import { contextBridge, ipcRenderer } from 'electron';
import type { DesktopApi } from './bridge.ts';

const api: DesktopApi = Object.freeze<DesktopApi>({
  security: Object.freeze({ sandboxed: process.sandboxed === true, isolated: process.contextIsolated === true }),
  inspect: () => ipcRenderer.invoke('runtime:inspect'),
  chooseProject: () => ipcRenderer.invoke('history:chooseProject'),
  listThreads: query => ipcRenderer.invoke('history:listThreads', query),
  listTurns: query => ipcRenderer.invoke('history:listTurns', query),
  listItems: query => ipcRenderer.invoke('history:listItems', query),
  workspaceState: () => ipcRenderer.invoke('execution:workspaceState'),
  listTasks:query=>ipcRenderer.invoke('tasks:list',query),
  applyTaskCommand:command=>ipcRenderer.invoke('tasks:command',command),
  startTask:input=>ipcRenderer.invoke('tasks:start',input),
  listTaskActivity:query=>ipcRenderer.invoke('tasks:activity',query),
  resourceBudget:()=>ipcRenderer.invoke('runtime:resourceBudget'),
  applyTaskPlan:input=>ipcRenderer.invoke('tasks:plan',input),
  listTaskPlans:query=>ipcRenderer.invoke('tasks:plans',query),
  cancelTaskPlan:query=>ipcRenderer.invoke('tasks:cancelPlan',query),
  getWorkspace:query=>ipcRenderer.invoke('workspace:overview',query),
  listWorkspaceDirectory:query=>ipcRenderer.invoke('workspace:directory',query),
  readWorkspaceFile:query=>ipcRenderer.invoke('workspace:file',query),
  getWorkspaceDiff:query=>ipcRenderer.invoke('workspace:diff',query),
  submitMessage: input => ipcRenderer.invoke('execution:submit', input),
  continueRun: input => ipcRenderer.invoke('execution:continue', input),
  listRuns: query => ipcRenderer.invoke('execution:list', query),
  getRun: query => ipcRenderer.invoke('execution:view', query),
  reconcileRun: query => ipcRenderer.invoke('execution:reconcile', query),
  listInteractions: query => ipcRenderer.invoke('execution:interactions', query),
  replyInteraction: input => ipcRenderer.invoke('execution:reply', input),
  getVerification: query => ipcRenderer.invoke('execution:review', query),
  verifyRun: query => ipcRenderer.invoke('execution:verify', query),
  interruptRun: query => ipcRenderer.invoke('execution:interrupt', query),
});
contextBridge.exposeInMainWorld('personalAgent', api);
